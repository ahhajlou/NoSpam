# tools/update-tlds.sh — refresh the domain endings that links in messages accept.
#
# A link written without "http://" (example.com, b2n.ir/x) is offered only when
# its last label is a real top-level domain, so that file.txt and report.pdf are
# not. The list is IANA's root zone list, written into TopLevelDomains.kt so the
# app needs no network for it. A stale list only leaves the newest endings
# unlinked. Run it now and then, look over the diff, run the tests and commit.
#
# Usage: tools/update-tlds.sh
set -euo pipefail

url="https://data.iana.org/TLD/tlds-alpha-by-domain.txt"
out="feature/thread/src/main/kotlin/com/nospam/nospam/feature/thread/TopLevelDomains.kt"
cd "$(dirname "$0")/.."

list=$(curl -fsS --max-time 30 "$url")
version=$(printf '%s\n' "$list" | sed -n '1s/^# Version \([0-9]*\).*/\1/p')
[ -n "$version" ] || { echo "error: no version line in $url" >&2; exit 1; }
domains=$(printf '%s\n' "$list" | grep -v '^#' | tr 'A-Z' 'a-z' | grep -E '^[a-z0-9-]+$')
count=$(printf '%s\n' "$domains" | wc -l | tr -d ' ')
# A truncated download must not quietly unlink most of the web.
[ "$count" -gt 1000 ] || { echo "error: only $count domains in $url" >&2; exit 1; }

{
    cat <<EOF
// SPDX-License-Identifier: GPL-3.0-or-later
// Generated by tools/update-tlds.sh from $url
// (version $version, $count domains). Do not edit by hand: run the script.

package com.nospam.nospam.feature.thread

/** The IANA root zone list [TOP_LEVEL_DOMAINS] was made from. */
internal const val TOP_LEVEL_DOMAINS_VERSION = "$version"

/** Every top-level domain, lowercase, internationalized ones in their xn-- form. */
internal val TOP_LEVEL_DOMAINS: Set<String> = """
EOF
    printf '%s\n' "$domains" | fmt -w 100
    cat <<'EOF'
""".split(' ', '\n').filterTo(HashSet()) { it.isNotEmpty() }
EOF
} > "$out"
echo "wrote $out: $count domains, IANA version $version"
